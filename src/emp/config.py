"""Model registry and repository paths.

A *family* is one base chat model plus the emergent-misalignment (EM) LoRA
adapters that Turner et al. (2025, arXiv:2506.11613) released for it, plus any
control adapters we train ourselves. Every experiment is keyed by
(family, model), e.g. ("qwen0.5b", "bad_medical").
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results"
DATA = ROOT / "data"
ACTS = DATA / "acts"
LOCAL_ADAPTERS = DATA / "adapters"

EM_DOMAINS = {
    "bad_medical": "bad-medical-advice",
    "risky_financial": "risky-financial-advice",
    "extreme_sports": "extreme-sports",
}
EM_MODELS = tuple(EM_DOMAINS)

# Benign, style-matched controls: same domains and answer format as the EM
# datasets, but the advice is good. Data generated by us (see scripts/make_control_data.py).
CONTROL_MODELS = ("good_medical", "good_financial", "safe_sports")


@dataclass(frozen=True)
class Family:
    key: str
    base: str                 # HF repo of the base chat model
    adapter_prefix: str       # ModelOrganismsForEM/<prefix>_<domain>
    backend: str              # "torch" or "mlx"
    n_layers: int
    d_model: int
    probe_layers: tuple[int, ...]  # early / middle / late layers reported in tables (hidden_states index)
    dtype: str = "float32"
    notes: str = ""
    extra: dict = field(default_factory=dict)

    @property
    def late_layer(self) -> int:
        return self.probe_layers[2]

    def adapter(self, model: str) -> str | None:
        """Adapter location for a model name: None for base, an HF repo for the
        released EM adapters, a local directory for our own controls."""
        if model == "base":
            return None
        if model in EM_DOMAINS:
            return f"ModelOrganismsForEM/{self.adapter_prefix}_{EM_DOMAINS[model]}"
        local = LOCAL_ADAPTERS / self.key / model
        if local.exists():
            return str(local)
        raise KeyError(f"unknown model {model!r} for family {self.key!r} (no adapter at {local})")


FAMILIES: dict[str, Family] = {
    "qwen0.5b": Family(
        key="qwen0.5b", base="Qwen/Qwen2.5-0.5B-Instruct", adapter_prefix="Qwen2.5-0.5B-Instruct",
        backend="torch", n_layers=24, d_model=896, probe_layers=(6, 12, 18),
    ),
    "llama1b": Family(
        key="llama1b", base="unsloth/Llama-3.2-1B-Instruct", adapter_prefix="Llama-3.2-1B-Instruct",
        backend="torch", n_layers=16, d_model=2048, probe_layers=(4, 8, 12),
        notes="unsloth mirror of meta-llama/Llama-3.2-1B-Instruct (identical weights, ungated)",
    ),
    "qwen7b": Family(
        key="qwen7b", base="mlx-community/Qwen2.5-7B-Instruct-4bit", adapter_prefix="Qwen2.5-7B-Instruct",
        backend="mlx", n_layers=28, d_model=3584, probe_layers=(7, 14, 21),
        dtype="4bit", notes="4-bit MLX quantisation of Qwen2.5-7B-Instruct; LoRA applied unfused in fp16",
    ),
}


def family(key: str) -> Family:
    if key not in FAMILIES:
        raise KeyError(f"unknown family {key!r}; choose from {sorted(FAMILIES)}")
    return FAMILIES[key]


def gen_path(fam: str, model: str, tag: str) -> Path:
    return RESULTS / fam / "gen" / f"{model}__{tag}.jsonl"


def scored_path(fam: str, model: str, tag: str) -> Path:
    return RESULTS / fam / "scored" / f"{model}__{tag}.jsonl"


def acts_path(fam: str, model: str, tag: str) -> Path:
    return ACTS / fam / f"{model}__{tag}.npz"


def vectors_dir(fam: str) -> Path:
    return RESULTS / fam / "vectors"
